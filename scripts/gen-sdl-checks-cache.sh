#!/usr/bin/env bash
# Records the results of SDL2's CMake feature checks (check_include_file, check_c_source_compiles, ...) from a
# finished Android configure into app/src/main/cpp/sdl2-android-checks.cmake, which uzdoom_hook.cmake then
# replays so that a re-configure skips ~180 try_compile runs.
#   usage: scripts/gen-sdl-checks-cache.sh [path/to/CMakeCache.txt]     (default: newest app/.cxx/**/CMakeCache.txt)
# Re-run it after changing the SDL submodule, the NDK, minSdk or the C++ STL; a stale file is ignored (its
# first line holds the toolchain key) and the checks run as before.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cache="${1:-}"
if [ -z "$cache" ]; then
  cache="$(find "$root/app/.cxx" -name CMakeCache.txt -print0 2>/dev/null | xargs -0 ls -t 2>/dev/null | head -1 || true)"
fi
[ -f "$cache" ] || { echo "no CMakeCache.txt found: build once first (./gradlew assembleDebug)" >&2; exit 1; }
out="$root/app/src/main/cpp/sdl2-android-checks.cmake"
python3 -I - "$cache" "$root/external/SDL" "$out" <<'PY'
import re, sys, pathlib
cache_path, sdl_dir, out = sys.argv[1:4]
entries = {}
for line in open(cache_path, encoding="utf-8", errors="replace"):
    m = re.match(r"^([A-Za-z0-9_.+-]+):(\w+)=(.*)$", line.rstrip("\n"))
    if m:
        entries[m.group(1)] = (m.group(2), m.group(3))
key = entries.get("DOOMXR_SDL_CHECKS_KEY")
if not key:
    sys.exit("DOOMXR_SDL_CHECKS_KEY missing from the cache: configure with the current uzdoom_hook.cmake first")
# Every identifier that appears in SDL's CMake files. try_compile based checks (check_include_file,
# check_c_source_compiles, ...) store their result as an INTERNAL cache entry named after the variable the
# project passed in, so INTERNAL entries that SDL mentions are exactly its recorded feature checks.
names = set()
files = [pathlib.Path(sdl_dir, "CMakeLists.txt")] + list(pathlib.Path(sdl_dir, "cmake").rglob("*.cmake"))
for f in files:
    if f.is_file():
        names.update(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", f.read_text(errors="replace")))
picked = sorted(n for n in names if n in entries and entries[n][0] == "INTERNAL"
                and not n.startswith(("CMAKE_", "DOOMXR_", "_")))
if len(picked) < 20:
    sys.exit(f"only {len(picked)} SDL check results found in the cache: refusing to write a useless file")
with open(out, "w") as o:
    o.write(f"# key: {key[1]}\n")
    o.write("# Generated by scripts/gen-sdl-checks-cache.sh; replayed by uzdoom_hook.cmake. Do not edit.\n")
    for n in picked:
        v = entries[n][1].replace("\\", "\\\\").replace('"', '\\"')
        o.write(f'set({n} "{v}" CACHE INTERNAL "")\n')
print(f"wrote {len(picked)} recorded SDL2 checks to {out}")
PY
